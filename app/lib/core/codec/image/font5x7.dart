/// Glyph columns (5 bytes) for a character; letters with accents use the base letter,
/// anything else outside printable ASCII becomes '?'.
List<int> glyph5x7(String ch) {
  var c = ch.runes.first;
  if (c < 0x20 || c > 0x7E) c = _fold[c] ?? 0x3F;
  final o = (c - 0x20) * 5;
  return font5x7.sublist(o, o + 5);
}
